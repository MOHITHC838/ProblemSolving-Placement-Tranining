package AssignmentOperator;

public class CompoundAssignment {
    public static void main(String[] args) {
        int initialvalue = 10;
       
        System.out.println(initialvalue +=3);
        System.out.println(initialvalue -3);
        System.out.println(initialvalue *3);
        System.out.println(initialvalue /3);
        System.out.println(initialvalue %3);

    }
    
}
