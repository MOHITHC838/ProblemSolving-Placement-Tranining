package Operator;

public class postiveNegative {
    public static void main(String[] args) {
        int input = -12;
        if (input<0) {
            System.out.println("negative");    
        }
        else if (input>0) {
            System.out.println("postive");            
        }
        else{
            System.out.println("zero");
        }
    }
}
